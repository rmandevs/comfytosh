#!/usr/bin/env python3
"""Build the Comfytosh Theme landing page into _site/.

Standard library only. The page is data driven:
  - palette.json  -> the theme colours used by the preview and the palette table
  - ports.json    -> the ports grid and the downloads
  - site/vendor/comfytosh/tokens.json -> tokens.css for the Comfytosh design system

Run from the repository root:  python3 scripts/build_site.py [--out _site]
"""
import argparse
import colorsys
import html
import json
import os
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
VENDOR = SITE / "vendor" / "comfytosh"
REPO = "https://github.com/" + os.environ.get("GITHUB_REPOSITORY", "vstrofago/comfytosh")
BRANCH = os.environ.get("SITE_BRANCH", "main")

FAMILIES = [
    ("case", "Case plastics", "The beige machine. Grounds of the Case flavor."),
    ("crt", "Screen glass", "Cabinet and glass greys. Grounds of the Screen flavor."),
    ("phosphor", "Phosphor greens", "The terminal glow: strings, success and the cursor."),
    ("amber", "Amber", "The amber monitor and warm earth."),
    ("signal", "Signal", "The loudest colours. One per view."),
    ("comfy", "Comfy cool hues", "Blue, purple, cyan and rose for a full syntax theme."),
    ("deep", "Deep", "Darker twins that hold 4.5:1 on beige. Text on Case."),
]
CATEGORY_COLOR = {
    "editor": "comfy-lilac",
    "terminal": "phosphor-celadon",
    "cli": "amber-custard",
    "app": "comfy-periwinkle",
    "desktop": "comfy-rose",
}
# The design system ships these weights; tokens.json lists the .ttf names, the site serves .woff2.
SHIPPED_FONTS = {
    "Geist-Regular", "Geist-Medium", "Geist-SemiBold", "Geist-Italic",
    "GeistMono-Regular", "GeistMono-Medium", "GeistMono-SemiBold", "GeistMono-Bold",
    "GeistPixel-Square",
    "IBMPlexSerif-Light", "IBMPlexSerif-Regular", "IBMPlexSerif-Italic", "IBMPlexSerif-SemiBold",
}

esc = html.escape


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# ── tokens.css for the design system, compiled the way the design system page does ──

def css_value(value):
    if isinstance(value, str) and value.startswith("{") and value.endswith("}"):
        return "var(--%s)" % value[1:-1]
    return value


def compile_tokens(tokens):
    themes = [t["id"] for t in tokens["color"]["themes"]]
    first = themes[0]

    def per_theme(entries):
        base, extra = [], {t: [] for t in themes[1:]}
        for tok in entries:
            v = tok["value"]
            if isinstance(v, str):
                base.append((tok["name"], css_value(v)))
                continue
            fv = v.get(first, next(iter(v.values())))
            base.append((tok["name"], css_value(fv)))
            for t in themes[1:]:
                if t in v and v[t] != fv:
                    extra[t].append((tok["name"], css_value(v[t])))
        return base, extra

    cbase, cextra = per_theme(tokens["color"]["tokens"])
    sbase, sextra = per_theme(tokens.get("shadow", {}).get("tokens", []))
    out = ["/* Generated by scripts/build_site.py from site/vendor/comfytosh/tokens.json. Do not edit. */"]
    out.append(':root, [data-theme="%s"] {' % first)
    out += ["  --%s: %s;" % kv for kv in cbase + sbase]
    out.append("}")
    for t in themes[1:]:
        out.append('[data-theme="%s"] {' % t)
        out += ["  --%s: %s;" % kv for kv in cextra[t] + sextra[t]]
        out.append("}")
    out.append(":root {")
    for fam in ("spacing", "radius"):
        out += ["  --%s: %s;" % (t["name"], t["value"]) for t in tokens.get(fam, {}).get("tokens", [])]
    for key, stack in tokens["type"]["families"].items():
        out.append("  --font-%s: %s;" % (key, stack))
    out.append("}")
    for font in tokens["type"]["fonts"]:
        stem = Path(font["file"]).stem
        if stem not in SHIPPED_FONTS:
            continue
        out.append(
            '@font-face { font-family: "%s"; src: url("fonts/%s.woff2") format("woff2"); '
            "font-weight: %s; font-style: %s; font-display: swap; }"
            % (font["family"], stem, font["weight"], font.get("style", "normal"))
        )
    return "\n".join(out) + "\n"


# ── theme.css: the theme's own colours, from palette.json ──

def compile_theme(palette):
    out = ["/* Generated by scripts/build_site.py from palette.json. Do not edit. */", ":root {"]
    out += ["  --%s: %s;" % kv for kv in palette["primitives"].items()]
    out.append("}")
    for fid, flavor in palette["flavors"].items():
        out.append('.th[data-flavor="%s"] {' % fid)
        out += ["  --th-%s: %s;" % kv for kv in flavor["roles"].items()]
        out.append("}")
    return "\n".join(out) + "\n"


# ── colour helpers ──

def rgb_of(hx):
    hx = hx.lstrip("#")
    return tuple(int(hx[i:i + 2], 16) for i in (0, 2, 4))


def fmt_rgb(hx):
    return "rgb(%d, %d, %d)" % rgb_of(hx)


def fmt_hsl(hx):
    r, g, b = (c / 255 for c in rgb_of(hx))
    h, l, s_ = colorsys.rgb_to_hls(r, g, b)
    return "hsl(%d, %d%%, %d%%)" % (round(h * 360) % 360, round(s_ * 100), round(l * 100))




# ── HTML fragments ──

def render_palette(palette):
    prims = palette["primitives"]
    rows = []
    for prefix, title, note in FAMILIES:
        names = [n for n in prims if n.split("-")[0] == prefix]
        if not names:
            continue
        rows.append('<tr class="fam"><th colspan="5" scope="rowgroup">{t} <span>{note}</span></th></tr>'.format(
            t=esc(title), note=esc(note)))
        for n in names:
            hx = prims[n]
            vals = "".join('<td><button type="button" data-copy="{v}">{v}</button></td>'.format(v=esc(v))
                           for v in (hx, fmt_rgb(hx), fmt_hsl(hx)))
            rows.append('<tr><td class="sw"><i style="--c:{hx}"></i></td><th scope="row">{n}</th>{vals}</tr>'.format(
                hx=esc(hx), n=esc(n), vals=vals))
    return "\n".join(rows)


def render_filters(registry):
    counts = {}
    for p in registry["ports"]:
        counts[p["category"]] = counts.get(p["category"], 0) + 1
    keys = ['<button class="key key--sm" type="button" aria-pressed="true" data-filter="all"><span class="key__face">All</span></button>']
    for key, label in registry["categories"].items():
        if key in counts:
            keys.append('<button class="key key--sm" type="button" aria-pressed="false" data-filter="{k}"><span class="key__face">{l}</span></button>'.format(
                k=esc(key), l=esc(label)))
    return "\n".join(keys)


def render_ports(registry):
    cats = registry["categories"]
    tiles = []
    for p in sorted(registry["ports"], key=lambda p: p["name"].lower()):
        search = " ".join([p["name"], p["id"], cats[p["category"]]] + p.get("aliases", [])).lower()
        tiles.append(
            '<article class="port" data-cat="{cat}" data-search="{search}">'
            '<span class="port__mark" style="--pm:var(--{color})" aria-hidden="true">{initial}</span>'
            '<div class="port__text"><h3 class="port__name"><a href="{repo}/blob/{branch}/{path}/README.md">{name}</a></h3>'
            '<span class="port__cat">{catlabel}</span></div>'
            '<a class="port__dl" href="downloads/comfytosh-{id}.zip" download aria-label="Download {name}" title="Download">'
            '<svg viewBox="0 0 16 16" width="18" height="18" aria-hidden="true"><path fill="currentColor" d="M2.75 14A1.75 1.75 0 0 1 1 12.25v-2.5a.75.75 0 0 1 1.5 0v2.5c0 .14.11.25.25.25h10.5a.25.25 0 0 0 .25-.25v-2.5a.75.75 0 0 1 1.5 0v2.5A1.75 1.75 0 0 1 13.25 14ZM7.25 7.69V2a.75.75 0 0 1 1.5 0v5.69l1.97-1.97a.75.75 0 1 1 1.06 1.06l-3.25 3.25a.75.75 0 0 1-1.06 0L4.22 6.78a.75.75 0 1 1 1.06-1.06Z"/></svg></a>'
            '</article>'.format(
                cat=esc(p["category"]), search=esc(search), color=CATEGORY_COLOR.get(p["category"], "crt-ash"),
                initial=esc(p["name"][0].upper()), name=esc(p["name"]), id=esc(p["id"]), repo=REPO, branch=BRANCH,
                path=esc(p["path"]),
                catlabel=esc(cats[p["category"]].rstrip("s") if p["category"] != "cli" else "Command line"),
            )
        )
    return "\n".join(tiles)


# ── build ──

def build(out):
    palette = load(ROOT / "palette.json")
    registry = load(ROOT / "ports.json")
    tokens = load(VENDOR / "tokens.json")

    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SITE, out, ignore=shutil.ignore_patterns("*.json", "*.md", "data"))
    (out / "vendor" / "comfytosh" / "tokens.css").write_text(compile_tokens(tokens), encoding="utf-8")
    (out / "assets" / "theme.css").write_text(compile_theme(palette), encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")

    for name in ("palette.json", "ports.json"):
        shutil.copy2(ROOT / name, out / name)
    downloads = out / "downloads"
    downloads.mkdir(exist_ok=True)
    for port in registry["ports"]:
        folder = ROOT / port["path"]
        with zipfile.ZipFile(downloads / ("comfytosh-%s.zip" % port["id"]), "w", zipfile.ZIP_DEFLATED) as one:
            for f in sorted(f for f in folder.rglob("*") if f.is_file()):
                one.write(f, f.relative_to(ROOT).as_posix())

    page = (SITE / "index.html").read_text(encoding="utf-8")
    replacements = {
        "<!-- @palette -->": render_palette(palette),
        "<!-- @filters -->": render_filters(registry),
        "<!-- @ports -->": render_ports(registry),
        "{{port_count}}": str(len(registry["ports"])),
        "{{repo}}": REPO,
        "{{branch}}": BRANCH,
    }
    for key, value in replacements.items():
        if key not in page:
            raise SystemExit("site/index.html is missing the placeholder " + key)
        page = page.replace(key, value)
    (out / "index.html").write_text(page, encoding="utf-8")
    print("Built %s: %d ports, %d colours" % (out.relative_to(ROOT) if out.is_relative_to(ROOT) else out, len(registry["ports"]), len(palette["primitives"])))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(ROOT / "_site"))
    build(Path(ap.parse_args().out).resolve())
